// Refreshes the S&P 500 member list the stock screener opens on (ADR 0030).
// Source: the public-domain (ODC-PDDL) dataset at github.com/datasets/s-and-p-500-companies,
// which follows Wikipedia's "List of S&P 500 companies". Run with:
//   pnpm --filter @tm/domain sp500:update
/* global URL, fetch, console */
import { writeFileSync } from 'node:fs';

const SOURCE =
  'https://raw.githubusercontent.com/datasets/s-and-p-500-companies/main/data/constituents.csv';
const OUT = new URL('../src/market/sp500-members.ts', import.meta.url);

/** One CSV line into fields, honouring double quotes. */
function fields(line) {
  const out = [];
  let cur = '';
  let quoted = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (quoted) {
      if (ch === '"' && line[i + 1] === '"') {
        cur += '"';
        i++;
      } else if (ch === '"') quoted = false;
      else cur += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ',') {
      out.push(cur);
      cur = '';
    } else cur += ch;
  }
  out.push(cur);
  return out;
}

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`The member list answered ${response.status}`);
const [header, ...lines] = (await response.text()).trim().split(/\r?\n/);
const cols = fields(header);
const symbolAt = cols.indexOf('Symbol');
const sectorAt = cols.indexOf('GICS Sector');
if (symbolAt < 0 || sectorAt < 0) throw new Error('The member list has changed shape');
const members = lines
  .map(fields)
  .map((f) => [f[symbolAt].trim().toUpperCase(), f[sectorAt].trim()])
  .filter(([s]) => /^[A-Z][A-Z0-9.]{0,9}$/.test(s))
  .sort((a, b) => a[0].localeCompare(b[0]));
if (members.length < 480 || members.length > 520) {
  throw new Error(`Expected about 503 members, got ${members.length}`);
}
const asOf = new Date().toISOString().slice(0, 10);
writeFileSync(
  OUT,
  `/**
 * S&P 500 members and their GICS sectors, for the stock screener (ADR 0030).
 * Generated by \`pnpm --filter @tm/domain sp500:update\` from the public-domain
 * dataset at github.com/datasets/s-and-p-500-companies; do not edit by hand.
 */

export const SP500_AS_OF = '${asOf}';

/** \`[symbol, sector]\`, symbols as Alpaca writes them (BRK.B). */
export const SP500_MEMBERS: readonly (readonly [string, string])[] = [
${members.map(([s, sector]) => `  [${JSON.stringify(s)}, ${JSON.stringify(sector)}],`).join('\n')}
];
`,
);
// eslint-disable-next-line no-console -- a command-line script reports what it wrote
console.log(`Wrote ${members.length} S&P 500 members as of ${asOf}`);
