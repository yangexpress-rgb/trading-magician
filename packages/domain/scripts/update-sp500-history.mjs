// Point-in-time S&P 500 membership (data inputs part 2, item C, N324, ADR 0112).
// Reads fja05680/sp500's "S&P 500 Historical Components & Changes (Updated).csv"
// from a local file a person downloaded (never fetched by the app) and writes
// src/market/groups/sp500-history.ts: one period per stretch a symbol was a
// member, [from, to), to null while it still is. The worker stores the periods
// in group_membership_period on its next start.
// Run with:
//   pnpm --filter @tm/domain groups:history --file "<path to the CSV>"
// The file: https://github.com/fja05680/sp500 (download it by hand).
/* global URL, console, process */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const args = process.argv.slice(2);
const at = args.indexOf('--file');
const path = at >= 0 ? args[at + 1] : undefined;
if (!path) {
  // eslint-disable-next-line no-console -- a command-line script says how to run it
  console.error(
    'Use: groups:history --file "<S&P 500 Historical Components & Changes (Updated).csv>"',
  );
  process.exit(1);
}
const raw = readFileSync(path);
const sha256 = createHash('sha256').update(raw).digest('hex');
const lines = raw
  .toString('utf8')
  .replace(/^\uFEFF/, '')
  .split(/\r?\n/)
  .filter((l) => l.trim() !== '');
const header = (lines.shift() ?? '').toLowerCase().replace(/\s/g, '');
if (header !== 'date,tickers') throw new Error(`Unexpected header "${header}" (want date,tickers)`);

/** Snapshots in date order: the full member list as of each date the file writes. */
const snapshots = [];
for (const line of lines) {
  const m = /^(\d{4}-\d{2}-\d{2}),"?([^"]*)"?$/.exec(line.trim());
  if (!m) throw new Error(`Unreadable row: ${line.slice(0, 80)}`);
  const symbols = new Set(
    m[2]
      .split(',')
      .map((s) => s.trim().toUpperCase())
      .filter((s) => /^[A-Z][A-Z0-9.]{0,9}$/.test(s)),
  );
  snapshots.push({ date: m[1], symbols });
}
snapshots.sort((a, b) => a.date.localeCompare(b.date));
if (snapshots.length < 100)
  throw new Error(`Only ${snapshots.length} snapshots; is this the right file?`);
const last = snapshots[snapshots.length - 1];
if (last.symbols.size < 490 || last.symbols.size > 510)
  throw new Error(`The last snapshot has ${last.symbols.size} members; expected about 500`);

// A symbol is a member from the first snapshot that lists it until the first that does not.
const open = new Map();
const periods = [];
let prev = new Set();
for (const { date, symbols } of snapshots) {
  for (const s of symbols) if (!prev.has(s)) open.set(s, date);
  for (const s of prev)
    if (!symbols.has(s)) {
      periods.push([s, open.get(s), date]);
      open.delete(s);
    }
  prev = symbols;
}
for (const [s, from] of open) periods.push([s, from, null]);
periods.sort((a, b) => a[0].localeCompare(b[0]) || a[1].localeCompare(b[1]));

const out = new URL('../src/market/groups/sp500-history.ts', import.meta.url);
writeFileSync(
  out,
  `/**
 * Point-in-time S&P 500 membership (ADR 0112), generated by
 * \`pnpm --filter @tm/domain groups:history --file <csv>\` from fja05680/sp500,
 * "S&P 500 Historical Components & Changes (Updated).csv"; do not edit by hand.
 */

export const SP500_HISTORY_SOURCE = 'fja05680-sp500';
/** The file's first and last snapshot dates. */
export const SP500_HISTORY_FROM = '${snapshots[0].date}';
export const SP500_HISTORY_THROUGH = '${last.date}';
/** The imported file's SHA-256, so a re-import of the same file changes nothing. */
export const SP500_HISTORY_SHA256 = '${sha256}';

/** \`[symbol, from, to]\`: a member from \`from\` until the day before \`to\`; \`to\` null while still one. */
export const SP500_HISTORY_PERIODS: readonly (readonly [string, string, string | null])[] = [
${periods.map((p) => `  ${JSON.stringify(p)},`).join('\n')}
];
`,
);
// pnpm puts the package's prettier on the PATH.
execFileSync('prettier', ['--write', out.pathname], { stdio: 'ignore' });
// eslint-disable-next-line no-console -- a command-line script reports what it wrote
console.log(
  `S&P 500 history: ${snapshots.length} snapshots ${snapshots[0].date}..${last.date}, ` +
    `${new Set(periods.map((p) => p[0])).size} symbols, ${periods.length} periods, ` +
    `${last.symbols.size} members on the last date`,
);
